CREATE INDEX idx_users_role ON users(role);

CREATE INDEX idx_specialist_profiles_moderation_status ON specialist_profiles(moderation_status);
CREATE INDEX idx_specialist_profiles_is_verified ON specialist_profiles(is_verified);
CREATE INDEX idx_specialist_profiles_average_rating ON specialist_profiles(average_rating);

CREATE INDEX idx_orders_status ON orders(status);
CREATE INDEX idx_orders_customer_id ON orders(customer_id);
CREATE INDEX idx_orders_specialist_id ON orders(specialist_id);
CREATE INDEX idx_orders_created_at ON orders(created_at);

CREATE INDEX idx_bids_order_id ON bids(order_id);
CREATE INDEX idx_bids_specialist_id ON bids(specialist_id);
CREATE INDEX idx_bids_is_selected ON bids(is_selected);

CREATE INDEX idx_reviews_specialist_id ON reviews(specialist_id);
CREATE INDEX idx_reviews_status ON reviews(status);
CREATE INDEX idx_reviews_rating ON reviews(rating);
CREATE INDEX idx_reviews_created_at ON reviews(created_at);